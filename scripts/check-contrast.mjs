// Проверка контраста текстовых пар дизайн-системы (WCAG 2.x, порог 4.5:1 для текста, 3:1 для крупного/UI).
// Запуск: npm run contrast
const hex = (h) => h.replace('#', '').match(/.{2}/g).map((x) => parseInt(x, 16) / 255);
const lin = (c) => (c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
const L = (h) => { const [r, g, b] = hex(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [L(a), L(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const PAIRS = [
  ['текст на светлом', '#12080b', '#f6f1ee', 4.5],
  ['приглушённый на светлом', '#5c4d4f', '#f6f1ee', 4.5],
  ['приглушённый на bone', '#5c4d4f', '#fffcfa', 4.5],
  ['бургунди-акцент на светлом', '#8a2040', '#f6f1ee', 4.5],
  ['aqua-text на светлом (подписи, единицы)', '#2b6675', '#f6f1ee', 4.5],
  ['aqua-600 на светлом — только линии/иконки', '#4e8c9c', '#f6f1ee', 3],
  ['текст на тёмном', '#fffcfa', '#350a16', 4.5],
  ['приглушённый на тёмном', '#d9c7cb', '#350a16', 4.5],
  ['wine-glow на тёмном — только линии/свечение', '#c4566e', '#350a16', 3],
  ['wine-text на тёмном (мелкий текст)', '#e39aab', '#350a16', 4.5],
  ['текст на ink', '#fffcfa', '#12080b', 4.5],
  ['приглушённый на ink', '#d9c7cb', '#12080b', 4.5],
  ['кнопка primary: bone на burgundy-700', '#fffcfa', '#6b1730', 4.5],
  ['кнопка on-dark: burgundy-900 на bone', '#350a16', '#fffcfa', 4.5],
  ['ошибка формы на тёмном', '#f2a3b3', '#350a16', 4.5],
  ['ошибка формы на светлом', '#b3213f', '#f6f1ee', 4.5],
  ['gold на светлом — только декоративные точки, не текст', '#c2a36b', '#f6f1ee', 1],
  ['плейсхолдер-баннер юр. документов', '#6b5322', '#f6f1ee', 4.5],
];

let fail = 0;
for (const [name, fg, bg, min] of PAIRS) {
  const r = ratio(fg, bg);
  const ok = r >= min;
  if (!ok) fail++;
  console.log(`${ok ? 'OK ' : 'FAIL'} ${r.toFixed(2)}:1  (min ${min})  ${name}  ${fg} / ${bg}`);
}
console.log(fail ? `\nНе прошли: ${fail}` : '\nВсе пары проходят порог.');
process.exit(fail ? 1 : 0);
