// Проверка контраста текстовых пар дизайн-системы (WCAG 2.x, порог 4.5:1 для текста, 3:1 для крупного/UI).
// Запуск: npm run contrast
const hex = (h) => h.replace('#', '').match(/.{2}/g).map((x) => parseInt(x, 16) / 255);
const lin = (c) => (c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
const L = (h) => { const [r, g, b] = hex(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [L(a), L(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const PAIRS = [
  ['текст на светлом', '#04141a', '#eef5f6', 4.5],
  ['приглушённый на светлом', '#4a5f66', '#eef5f6', 4.5],
  ['приглушённый на bone', '#4a5f66', '#fbfdfd', 4.5],
  ['deep-600 на светлом (роли, акценты)', '#136a7c', '#eef5f6', 4.5],
  ['aqua-text на светлом (подписи, единицы)', '#1c6272', '#eef5f6', 4.5],
  ['aqua-600 на светлом — только линии/иконки', '#2b93a8', '#eef5f6', 3],
  ['текст на тёмном', '#fbfdfd', '#07313b', 4.5],
  ['приглушённый на тёмном', '#c3dbe0', '#07313b', 4.5],
  ['glow на тёмном — только линии/свечение', '#4fc3d6', '#07313b', 3],
  ['glow-text на тёмном (мелкий текст)', '#9fe2ec', '#07313b', 4.5],
  ['текст на ink', '#fbfdfd', '#04141a', 4.5],
  ['приглушённый на ink', '#c3dbe0', '#04141a', 4.5],
  ['кнопка primary: bone на deep-700', '#fbfdfd', '#0d4f5e', 4.5],
  ['кнопка on-dark: deep-900 на bone', '#07313b', '#fbfdfd', 4.5],
  ['ошибка формы на тёмном', '#f2a3b3', '#07313b', 4.5],
  ['ошибка формы на светлом', '#b3213f', '#eef5f6', 4.5],
  ['gold на светлом — только декоративные точки, не текст', '#c2a36b', '#eef5f6', 1],
  ['плейсхолдер-баннер юр. документов', '#6b5322', '#eef5f6', 4.5],
];

let fail = 0;
for (const [name, fg, bg, min] of PAIRS) {
  const r = ratio(fg, bg);
  const ok = r >= min;
  if (!ok) fail++;
  console.log(`${ok ? 'OK ' : 'FAIL'} ${r.toFixed(2)}:1  (min ${min})  ${name}  ${fg} / ${bg}`);
}
console.log(fail ? `\nНе прошли: ${fail}` : '\nВсе пары проходят порог.');
process.exit(fail ? 1 : 0);
